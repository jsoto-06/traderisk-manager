const translations: Record<Locale, Translations> = { es, en };

export function getTranslations(locale: Locale): Translations {
  return translations[locale] || translations.es;
}

export function formatCurrency(value: number, currency: string = 'USD', locale: Locale = 'es'): string {
  const loc = locale === 'es' ? 'es-MX' : 'en-US';
  try {
    return new Intl.NumberFormat(loc, {
      style: 'currency',
      currency,
      minimumFractionDigits: 2,
      maximumFractionDigits: 2,
    }).format(value);
  } catch {
    return `${currency} ${value.toFixed(2)}`;
  }
}

export function formatPercent(value: number, locale: Locale = 'es'): string {
  const loc = locale === 'es' ? 'es-MX' : 'en-US';
  return new Intl.NumberFormat(loc, {
    style: 'percent',
    minimumFractionDigits: 2,
    maximumFractionDigits: 2,
  }).format(value / 100);
}

export function formatDate(dateStr: string, locale: Locale = 'es'): string {
  const loc = locale === 'es' ? 'es-MX' : 'en-US';
  try {
    return new Intl.DateTimeFormat(loc, {
      year: 'numeric',
      month: 'short',
      day: 'numeric',
    }).format(new Date(dateStr));
  } catch {
    return dateStr;
  }
}

export function formatDateTime(dateStr: string, locale: Locale = 'es'): string {
  const loc = locale === 'es' ? 'es-MX' : 'en-US';
  try {
    return new Intl.DateTimeFormat(loc, {
      year: 'numeric',
      month: 'short',
      day: 'numeric',
      hour: '2-digit',
      minute: '2-digit',
    }).format(new Date(dateStr));
  } catch {
    return dateStr;
  }
}

export function formatNumber(value: number, locale: Locale = 'es', decimals: number = 2): string {
  const loc = locale === 'es' ? 'es-MX' : 'en-US';
  return new Intl.NumberFormat(loc, {
    minimumFractionDigits: decimals,
    maximumFractionDigits: decimals,
  }).format(value);
}
